/// <summary>
/// Defines the categories used to classify tasks by area of life.
/// </summary>
public enum Category
{
    /// <summary>Tasks related to professional or job responsibilities.</summary>
    Work,

    /// <summary>Tasks related to education or self-learning.</summary>
    Study,

    /// <summary>Tasks related to household chores or home management.</summary>
    Home,

    /// <summary>Tasks related to personal goals or self-care.</summary>
    Personal,

    /// <summary>Tasks related to hobbies or recreational activities.</summary>
    Hobby,

    /// <summary>Tasks that do not fit into any other category.</summary>
    Other
}